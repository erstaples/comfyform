// Package codegen turns a ComfyUI schema into typed Go bindings.
package codegen

import (
	"bytes"
	"fmt"
	"go/format"
	"math"
	"sort"
	"strconv"
	"strings"

	"github.com/erstaples/comfyform/schema"
)

const (
	graphPkg = "github.com/erstaples/comfyform/graph"
	comfyPkg = "github.com/erstaples/comfyform/comfy"
)

// Generate returns a gofmt'd Go file with one constructor per node class.
func Generate(s *schema.Schema, pkg string) ([]byte, error) {
	names := Resolve(s)
	var b bytes.Buffer
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	w("// Code generated by comfy gen. DO NOT EDIT.\n// Regenerate after installing or updating custom nodes.\n\n")
	w("package %s\n\nimport (\n\t%q\n\t%q\n)\n\n", pkg, graphPkg, comfyPkg)
	w("var _ = graph.Bool\n\n")

	// marker types
	types := map[string]bool{}
	for _, cn := range s.Names() {
		c := s.Classes[cn]
		for _, in := range c.Inputs {
			if in.Kind == schema.KindLink {
				if t := TypeName(in.Type); t != "" {
					types[t] = true
				}
			}
		}
		for _, o := range c.Outputs {
			if t := TypeName(o.Type); t != "" {
				types[t] = true
			}
		}
	}
	tl := make([]string, 0, len(types))
	for t := range types {
		tl = append(tl, t)
	}
	sort.Strings(tl)
	w("// Socket marker types. graph.Ref[MODEL] only connects to MODEL inputs.\ntype (\n")
	for _, t := range tl {
		w("\t%s struct{}\n", t)
	}
	w(")\n\n")

	for _, cn := range s.Names() {
		if err := genClass(&b, s.Classes[cn], names[cn]); err != nil {
			return nil, fmt.Errorf("%s: %w", cn, err)
		}
	}

	out, err := format.Source(b.Bytes())
	if err != nil {
		return b.Bytes(), fmt.Errorf("gofmt: %w", err)
	}
	return out, nil
}

func genClass(b *bytes.Buffer, c *schema.Class, nm *Names) error {
	w := func(format string, args ...any) { fmt.Fprintf(b, format, args...) }

	title := c.DisplayName
	if title == "" {
		title = c.Name
	}
	w("// %s is %q (%s).\n", nm.Args, title, c.Category)
	w("// Zero values mean the schema default; set Raw to force a literal zero or to\n// wire a link into a widget input.\n")
	w("type %s struct {\n", nm.Args)
	for _, in := range c.Inputs {
		w("\t%s %s %s\n", nm.Inputs[in.Name], goType(in), fieldComment(in))
	}
	w("\tRaw graph.Inputs\n}\n\n")

	w("// %s holds the outputs of %q.\n", nm.Out, c.Name)
	w("type %s struct {\n\tNode string\n", nm.Out)
	for i, o := range c.Outputs {
		w("\t%s %s\n", nm.Outputs[i], refType(o.Type))
	}
	w("}\n\n")

	w("// %s adds a %q node named name.\n", nm.Func, c.Name)
	w("func %s(ctx *comfy.Context, name string, a %s) %s {\n", nm.Func, nm.Args, nm.Out)
	w("\tin := graph.Inputs{}\n")
	for _, in := range c.Inputs {
		f := "a." + nm.Inputs[in.Name]
		switch in.Kind {
		case schema.KindLink:
			arg := f
			if TypeName(in.Type) != "" {
				// a zero typed Ref is unset; pass nil so SetLink sees it as missing
				w("\tif %s.IsSet() {\n\t\tcomfy.SetLink(ctx, in, name, %q, %s, false)\n\t}", f, in.Name, f)
				if in.Required {
					w(" else {\n\t\tcomfy.SetLink(ctx, in, name, %q, nil, true)\n\t}\n", in.Name)
				} else {
					w("\n")
				}
				continue
			}
			w("\tcomfy.SetLink(ctx, in, name, %q, %s, %v)\n", in.Name, arg, in.Required)
		case schema.KindBool:
			def, _ := in.Default.(bool)
			w("\tcomfy.SetBool(in, %q, %s, %v, %v, %v)\n", in.Name, f, def, in.HasDefault, in.Required)
		case schema.KindAnyCombo:
			w("\tcomfy.SetAny(in, %q, %s, %s, %v, %v)\n", in.Name, f, literal(in.Default), in.HasDefault, in.Required)
		default:
			def := zeroLit(in.Kind)
			if in.HasDefault {
				if l, ok := typedLiteral(in); ok {
					def = l
				}
			}
			w("\tcomfy.SetValue(in, %q, %s, %s, %v, %v)\n", in.Name, f, def, in.HasDefault, in.Required)
		}
	}
	w("\tid := ctx.Node(name, %q, in, a.Raw)\n", c.Name)
	w("\treturn %s{Node: id", nm.Out)
	for i, o := range c.Outputs {
		w(", %s: graph.MakeRef[%s](id, %d)", nm.Outputs[i], markerOrAny(o.Type), i)
	}
	w("}\n}\n\n")
	return nil
}

func goType(in schema.Input) string {
	switch in.Kind {
	case schema.KindLink:
		return refType(in.Type)
	case schema.KindInt:
		return "int64"
	case schema.KindFloat:
		return "float64"
	case schema.KindBool:
		return "*bool"
	case schema.KindAnyCombo:
		return "any"
	default:
		return "string"
	}
}

func refType(t string) string {
	if n := TypeName(t); n != "" {
		return "graph.Ref[" + n + "]"
	}
	return "graph.AnyRef"
}

func markerOrAny(t string) string {
	if n := TypeName(t); n != "" {
		return n
	}
	return "struct{}"
}

func fieldComment(in schema.Input) string {
	var parts []string
	if !in.Required {
		parts = append(parts, "optional")
	}
	if in.Kind == schema.KindLink {
		parts = append(parts, in.Type)
	}
	if in.HasDefault {
		parts = append(parts, "default "+literal(in.Default))
	}
	if in.Min != nil || in.Max != nil {
		parts = append(parts, "range "+bound(in.Min, "-inf")+".."+bound(in.Max, "inf"))
	}
	if (in.Kind == schema.KindCombo || in.Kind == schema.KindAnyCombo) && len(in.Options) > 0 {
		if in.IsFileList() {
			parts = append(parts, fmt.Sprintf("one of %d files", len(in.Options)))
		} else {
			opts := make([]string, 0, len(in.Options))
			for _, o := range in.Options {
				opts = append(opts, fmt.Sprint(o))
			}
			s := strings.Join(opts, "|")
			if len(s) > 80 {
				s = s[:77] + "..."
			}
			parts = append(parts, s)
		}
	}
	if len(parts) == 0 {
		return ""
	}
	return "// " + strings.Join(parts, ", ")
}

func bound(f *float64, inf string) string {
	if f == nil {
		return inf
	}
	return strconv.FormatFloat(*f, 'f', -1, 64)
}

func zeroLit(k schema.Kind) string {
	switch k {
	case schema.KindInt:
		return "int64(0)"
	case schema.KindFloat:
		return "float64(0)"
	default:
		return `""`
	}
}

func typedLiteral(in schema.Input) (string, bool) {
	switch in.Kind {
	case schema.KindInt:
		f, ok := in.Default.(float64)
		if !ok || f > math.MaxInt64 || f < math.MinInt64 {
			return "", false
		}
		return fmt.Sprintf("int64(%d)", int64(f)), true
	case schema.KindFloat:
		f, ok := in.Default.(float64)
		if !ok {
			return "", false
		}
		return fmt.Sprintf("float64(%s)", strconv.FormatFloat(f, 'g', -1, 64)), true
	case schema.KindString, schema.KindCombo:
		s, ok := in.Default.(string)
		if !ok {
			return "", false
		}
		return strconv.Quote(s), true
	}
	return "", false
}

// literal renders a JSON-decoded value as Go source.
func literal(v any) string {
	switch t := v.(type) {
	case nil:
		return "nil"
	case string:
		return strconv.Quote(t)
	case bool:
		return strconv.FormatBool(t)
	case float64:
		if t == math.Trunc(t) && math.Abs(t) < 1e15 {
			return strconv.FormatInt(int64(t), 10)
		}
		return strconv.FormatFloat(t, 'g', -1, 64)
	default:
		return fmt.Sprintf("%#v", t)
	}
}
